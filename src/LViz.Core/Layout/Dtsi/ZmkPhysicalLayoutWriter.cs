using System.Globalization;
using System.Text;
using LViz.Core.Persistence;

namespace LViz.Core.Layout.Dtsi;

/// <summary>What <see cref="ZmkPhysicalLayoutWriter.WriteNextTo"/> did with the file.</summary>
public enum DtsiExportOutcome
{
    /// <summary>The file was written (new, or replacing an earlier LViz export).</summary>
    Written,

    /// <summary>A <c>&lt;id&gt;.dtsi</c> exists but LViz did not write it — left untouched.</summary>
    SkippedNotGenerated,

    /// <summary>No file existed and the caller did not allow creating one.</summary>
    SkippedMissing,
}

/// <summary>
/// Exports a <see cref="UserLayoutFile"/> as a <c>zmk,physical-layout</c> dtsi —
/// the firmware-facing twin of the <c>&lt;id&gt;.layout.json</c>. Pure text in,
/// pure text out for <see cref="Write"/>; <see cref="WriteNextTo"/> adds only the
/// file rule around it.
/// <para>
/// The output round-trips through <c>PhysicalLayoutImporter.Import</c> field for
/// field, so an exported file can be re-imported without loss. Every generated
/// file starts with <see cref="GeneratedMarker"/> and
/// <see cref="WriteNextTo"/> only ever replaces a file carrying that marker:
/// a hand-written dtsi of the same name is never overwritten.
/// </para>
/// </summary>
public static class ZmkPhysicalLayoutWriter
{
    /// <summary>
    /// First-line marker of a file LViz generated. A user who wants to keep
    /// their own edits deletes this line and the file becomes theirs.
    /// </summary>
    public const string GeneratedMarker = "/* Generated by LViz";

    /// <summary>
    /// Renders <paramref name="layout"/> as dtsi text (<c>\n</c> line endings,
    /// final newline). The node label is derived from the id (devicetree labels
    /// cannot contain <c>-</c> or start with a digit), and a
    /// <c>"</c> in the display name becomes <c>'</c> because the importer's
    /// <c>display-name</c> regex stops at the first quote.
    /// </summary>
    public static string Write(UserLayoutFile layout)
    {
        var label = Label(layout.Id);
        var name = layout.Name.Replace('"', '\'');

        var sb = new StringBuilder();
        sb.Append("/* Generated by LViz from ").Append(layout.Id)
          .Append(".layout.json. LViz rewrites this file when the layout is saved again; ")
          .Append("delete this line to keep your own changes. */\n");
        sb.Append("/* Add transform = <&...>; (and kscan, if your board needs it) ")
          .Append("to the node before using it in firmware. */\n");
        sb.Append('\n');
        sb.Append("#include <physical_layouts.dtsi>\n");
        sb.Append('\n');
        sb.Append("/ {\n");
        sb.Append("    ").Append(label).Append(": ").Append(label).Append(" {\n");
        sb.Append("        compatible = \"zmk,physical-layout\";\n");
        sb.Append("        display-name = \"").Append(name).Append("\";\n");
        sb.Append('\n');
        sb.Append("        keys  //                     w   h    x    y     rot    rx    ry\n");
        for (var i = 0; i < layout.Keys.Count; i++)
        {
            var key = layout.Keys[i];
            sb.Append(i == 0 ? "            = <&key_physical_attrs " : "            , <&key_physical_attrs ");
            sb.Append(Field(key.W)).Append(' ')
              .Append(Field(key.H)).Append(' ')
              .Append(Field(key.X)).Append(' ')
              .Append(Field(key.Y)).Append(' ')
              .Append(Field(key.R)).Append(' ')
              .Append(Field(key.Rx)).Append(' ')
              .Append(Field(key.Ry))
              .Append(">\n");
        }
        sb.Append("            ;\n");
        sb.Append("    };\n");
        sb.Append("};\n");
        return sb.ToString();
    }

    /// <summary>
    /// Whether <paramref name="text"/> looks like a file this writer produced:
    /// its first line, leading whitespace trimmed, starts with
    /// <see cref="GeneratedMarker"/> (ordinal).
    /// </summary>
    public static bool IsGeneratedByLviz(string text)
    {
        var newline = text.IndexOf('\n');
        var firstLine = (newline >= 0 ? text[..newline] : text).AsSpan().TrimStart();
        return firstLine.StartsWith(GeneratedMarker, StringComparison.Ordinal);
    }

    /// <summary>Where <see cref="WriteNextTo"/> writes the export for this id.</summary>
    public static string PathFor(string id, string directory) =>
        Path.Combine(directory, id + ".dtsi");

    /// <summary>
    /// Writes <c>&lt;id&gt;.dtsi</c> into <paramref name="directory"/> next to
    /// the layout's <c>.layout.json</c>. An existing file is replaced only when
    /// <see cref="IsGeneratedByLviz"/> says LViz wrote it; a missing file is
    /// created (directory included) only when <paramref name="createIfMissing"/>.
    /// IO exceptions propagate — the callers already handle them for the
    /// layout save itself.
    /// </summary>
    public static DtsiExportOutcome WriteNextTo(
        UserLayoutFile layout, string directory, bool createIfMissing)
    {
        var path = PathFor(layout.Id, directory);

        if (File.Exists(path))
        {
            if (!IsGeneratedByLviz(File.ReadAllText(path)))
                return DtsiExportOutcome.SkippedNotGenerated;
        }
        else
        {
            if (!createIfMissing)
                return DtsiExportOutcome.SkippedMissing;
            Directory.CreateDirectory(directory);
        }

        AtomicFile.WriteAllText(path, Write(layout));
        return DtsiExportOutcome.Written;
    }

    /// <summary>id <c>my-board</c> → <c>my_board_layout</c>; an id starting with
    /// a digit gets the <c>lviz_</c> prefix because devicetree labels must not
    /// start with one.</summary>
    private static string Label(string id)
    {
        var label = id.Replace('-', '_') + "_layout";
        return char.IsAsciiDigit(label[0]) ? "lviz_" + label : label;
    }

    /// <summary>Devicetree cell values: negatives only as <c>(-N)</c>.</summary>
    private static string Field(int value) =>
        value < 0
            ? "(-" + (-value).ToString(CultureInfo.InvariantCulture) + ")"
            : value.ToString(CultureInfo.InvariantCulture);
}
