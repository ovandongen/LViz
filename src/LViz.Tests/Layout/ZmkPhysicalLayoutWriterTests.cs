using LViz.Core.Layout;
using LViz.Core.Layout.Dtsi;
using LViz.Core.Layout.Import;
using Xunit;

namespace LViz.Tests.Layout;

/// <summary>
/// The <c>&lt;id&gt;.dtsi</c> export: house-format text, label/name sanitising,
/// lossless round trip through <see cref="PhysicalLayoutImporter"/>, the
/// generated-file marker check, and the never-overwrite-a-user-file rule of
/// <see cref="ZmkPhysicalLayoutWriter.WriteNextTo"/>.
/// </summary>
public sealed class ZmkPhysicalLayoutWriterTests : IDisposable
{
    private readonly string _dir;

    public ZmkPhysicalLayoutWriterTests()
    {
        _dir = Path.Combine(Path.GetTempPath(), $"lviz-dtsi-export-{Guid.NewGuid():N}");
        Directory.CreateDirectory(_dir);
    }

    public void Dispose()
    {
        if (Directory.Exists(_dir))
            Directory.Delete(_dir, recursive: true);
    }

    // --- Write ---

    [Fact]
    public void Write_TwoKeys_WritesLabelSanitisedNameAndNegativeParens()
    {
        var text = ZmkPhysicalLayoutWriter.Write(TwoKeyLayout());

        Assert.StartsWith(ZmkPhysicalLayoutWriter.GeneratedMarker, text, StringComparison.Ordinal);
        Assert.Contains("my_board_layout: my_board_layout {", text, StringComparison.Ordinal);
        Assert.Contains("display-name = \"My 'Board'\";", text, StringComparison.Ordinal);

        var lines = text.Split('\n');
        Assert.Contains("            = <&key_physical_attrs 100 100 0 0 0 0 0>", lines);
        Assert.Contains(
            "            , <&key_physical_attrs 150 100 (-150) 25 (-1500) (-75) 75>", lines);
    }

    [Fact]
    public void Write_ProducesTheExactHouseFormatDocument()
    {
        // Pins "exactly these lines": \\n endings, blank lines, indentation and
        // the fixed keys comment, byte for byte.
        var expected = string.Join('\n',
            "/* Generated by LViz from my-board.layout.json. LViz rewrites this file when the layout is saved again; delete this line to keep your own changes. */",
            "/* Add transform = <&...>; (and kscan, if your board needs it) to the node before using it in firmware. */",
            "",
            "#include <physical_layouts.dtsi>",
            "",
            "/ {",
            "    my_board_layout: my_board_layout {",
            "        compatible = \"zmk,physical-layout\";",
            "        display-name = \"My 'Board'\";",
            "",
            "        keys  //                     w   h    x    y     rot    rx    ry",
            "            = <&key_physical_attrs 100 100 0 0 0 0 0>",
            "            , <&key_physical_attrs 150 100 (-150) 25 (-1500) (-75) 75>",
            "            ;",
            "    };",
            "};",
            ""); // the trailing empty element is the final newline

        Assert.Equal(expected, ZmkPhysicalLayoutWriter.Write(TwoKeyLayout()));
        Assert.DoesNotContain("\r", expected, StringComparison.Ordinal);
    }

    [Fact]
    public void Write_IdStartingWithDigit_PrefixesLabelWithLviz()
    {
        var layout = TwoKeyLayout() with { Id = "60-percent" };

        var text = ZmkPhysicalLayoutWriter.Write(layout);

        Assert.Contains("lviz_60_percent_layout: lviz_60_percent_layout {", text, StringComparison.Ordinal);
    }

    // --- round trip ---

    [Fact]
    public void RoundTrip_TwoKeyLayout_KeepsNameAndEveryKeyField()
    {
        var layout = TwoKeyLayout();

        var imported = Assert.Single(PhysicalLayoutImporter.Import(
            ZmkPhysicalLayoutWriter.Write(layout)));

        // The importer names by display-name, which carries the sanitised name
        // (a '"' can never survive a dtsi string).
        Assert.Equal("My 'Board'", imported.Name);
        AssertSameKeyFields(layout.Keys, imported.Keys);
    }

    [Fact]
    public void RoundTrip_FortyTwoKeyGeneratedGrid_KeepsEveryKeyField()
    {
        var grid = GridLayoutGenerator.Generate(new(true, 18, 6, 3));
        var keys = grid.Keys
            .Select(k => new UserLayoutKey(k.X, k.Y, k.Width, k.Height, k.Rotation, k.Rx, k.Ry, Hand.Left))
            .ToList();
        var layout = new UserLayoutFile(
            UserLayoutFile.CurrentSchemaVersion, "generated-grid", "Generated grid", null, keys);
        Assert.Equal(42, keys.Count);

        var imported = Assert.Single(PhysicalLayoutImporter.Import(
            ZmkPhysicalLayoutWriter.Write(layout)));

        Assert.Equal("Generated grid", imported.Name);
        AssertSameKeyFields(keys, imported.Keys);
    }

    // --- IsGeneratedByLviz ---

    [Fact]
    public void IsGeneratedByLviz_TrueForWrittenText_EvenWithLeadingWhitespace()
    {
        var text = ZmkPhysicalLayoutWriter.Write(TwoKeyLayout());

        Assert.True(ZmkPhysicalLayoutWriter.IsGeneratedByLviz(text));
        Assert.True(ZmkPhysicalLayoutWriter.IsGeneratedByLviz("   " + text));
        Assert.True(ZmkPhysicalLayoutWriter.IsGeneratedByLviz("\t" + text));
    }

    [Fact]
    public void IsGeneratedByLviz_FalseForHandwrittenAndEmpty()
    {
        var corneStyle =
            "// Corne (foostan/corne) 6-column physical layout.\n" +
            "\n" +
            "/ {\n" +
            "    foostan_corne_6col_layout: foostan_corne_6col_layout {\n" +
            "        compatible = \"zmk,physical-layout\";\n" +
            "    };\n" +
            "};\n";

        Assert.False(ZmkPhysicalLayoutWriter.IsGeneratedByLviz(corneStyle));
        Assert.False(ZmkPhysicalLayoutWriter.IsGeneratedByLviz(""));
    }

    // --- WriteNextTo ---

    [Fact]
    public void WriteNextTo_MissingFileWithCreateIfMissing_CreatesDirectoryAndFile()
    {
        var nested = Path.Combine(_dir, "board-folder");

        var outcome = ZmkPhysicalLayoutWriter.WriteNextTo(TwoKeyLayout(), nested, createIfMissing: true);

        Assert.Equal(DtsiExportOutcome.Written, outcome);
        Assert.Equal(
            ZmkPhysicalLayoutWriter.Write(TwoKeyLayout()),
            File.ReadAllText(Path.Combine(nested, "my-board.dtsi")));
    }

    [Fact]
    public void WriteNextTo_MissingFileWithoutCreateIfMissing_CreatesNothing()
    {
        var nested = Path.Combine(_dir, "board-folder");

        var outcome = ZmkPhysicalLayoutWriter.WriteNextTo(TwoKeyLayout(), nested, createIfMissing: false);

        Assert.Equal(DtsiExportOutcome.SkippedMissing, outcome);
        Assert.False(File.Exists(Path.Combine(nested, "my-board.dtsi")));
        Assert.False(Directory.Exists(nested));
    }

    [Fact]
    public void WriteNextTo_ExistingGeneratedFile_ReplacesWithNewLayout()
    {
        var first = TwoKeyLayout();
        var second = new UserLayoutFile(
            UserLayoutFile.CurrentSchemaVersion, first.Id, "Renamed", null,
            [new UserLayoutKey(700, 300, 150, 100, 900, 750, 350, Hand.Right)]);
        ZmkPhysicalLayoutWriter.WriteNextTo(first, _dir, createIfMissing: true);

        var outcome = ZmkPhysicalLayoutWriter.WriteNextTo(second, _dir, createIfMissing: false);

        Assert.Equal(DtsiExportOutcome.Written, outcome);
        Assert.Equal(
            ZmkPhysicalLayoutWriter.Write(second),
            File.ReadAllText(Path.Combine(_dir, "my-board.dtsi")));
    }

    [Fact]
    public void WriteNextTo_ExistingUserFile_LeavesItByteForByteUntouched()
    {
        var path = Path.Combine(_dir, "my-board.dtsi");
        File.WriteAllText(path, "/ { };");
        var before = File.ReadAllBytes(path);

        var outcome = ZmkPhysicalLayoutWriter.WriteNextTo(TwoKeyLayout(), _dir, createIfMissing: true);

        Assert.Equal(DtsiExportOutcome.SkippedNotGenerated, outcome);
        Assert.Equal(before, File.ReadAllBytes(path));
    }

    // --- fixtures ---

    private static UserLayoutFile TwoKeyLayout() => new(
        UserLayoutFile.CurrentSchemaVersion, "my-board", "My \"Board\"", null,
        [
            new UserLayoutKey(0, 0, 100, 100, 0, 0, 0, Hand.Left),
            new UserLayoutKey(-150, 25, 150, 100, -1500, -75, 75, Hand.Right),
        ]);

    private static void AssertSameKeyFields(
        IReadOnlyList<UserLayoutKey> expected, IReadOnlyList<DtsiKeyPhysical> actual)
    {
        Assert.Equal(expected.Count, actual.Count);
        for (var i = 0; i < expected.Count; i++)
        {
            var e = expected[i];
            var a = actual[i];
            Assert.Equal(e.W, a.Width);
            Assert.Equal(e.H, a.Height);
            Assert.Equal(e.X, a.X);
            Assert.Equal(e.Y, a.Y);
            Assert.Equal(e.R, a.Rotation);
            Assert.Equal(e.Rx, a.Rx);
            Assert.Equal(e.Ry, a.Ry);
        }
    }
}
